#include <iostream>
using namespace std;
int main()
{
    int a=25;
    int b=7;
    int sum=a+b;
    int difference=a-b;
    int product=a*b;
    int division=a/b;
    int remainder=a%b;
    cout<<"Sum: "<<sum<<endl;
    cout<<"Difference: "<<difference<<endl;
    cout<<"Product: "<<product<<endl;
    cout<<"Division: "<<division<<endl;
    cout<<"Remainder:"<<remainder<<endl;

    return 0; 
}